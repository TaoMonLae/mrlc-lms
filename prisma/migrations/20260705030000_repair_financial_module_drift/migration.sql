-- where these tables already existed (in an earlier, narrower form) before
-- some of these columns were added to schema.prisma / this migration file.
-- CREATE TABLE IF NOT EXISTS cannot retroactively add columns to a table
-- that already exists, so if the migration was first applied before a
-- column existed in the file, that column silently never got created --
-- this is exactly what happened with Donor.isActive (P2022 column not
-- found) and ExpenseStatus.PARTIAL (separately fixed). ADD COLUMN IF NOT
-- EXISTS is idempotent and safe to run against any state of these tables.
-- NOT NULL columns get a placeholder DEFAULT purely so this can safely
-- backfill existing rows if the column is genuinely missing; the
-- application always supplies real values on every insert/update.

