-- Repair migration for the "add_financial_modules" migration's known
-- application-drift bugs.
--
-- That migration's CREATE TABLE IF NOT EXISTS / CREATE TYPE statements were
-- edited multiple times while schema.prisma was being filled out, but on a
-- database where a table/type already existed from an earlier, narrower
-- version of that same migration, those statements silently no-op instead of
-- adding the new columns/enum values -- CREATE TABLE/TYPE cannot retroactively
-- alter something that already exists.
--
-- Two concrete symptoms of this already surfaced in production:
--   - "column Donor.isActive does not exist" (P2022) -- donors/donations
--     failing to load.
--   - "invalid input value for enum ExpenseStatus: PARTIAL" (P2007) -- every
--     financial report failing.
--
-- Rather than fix these one at a time as they're discovered, this migration
-- exhaustively backfills every column and every enum value that migration
-- ever defined, via ADD COLUMN IF NOT EXISTS / ADD VALUE IF NOT EXISTS --
-- both fully idempotent and safe to run against a table/type in any state.
-- NOT NULL columns without an original default get a placeholder default
-- purely so this can safely backfill any existing rows if the column really
-- is missing; the application always supplies real values on every write.
--
-- Requires PostgreSQL 12+ for ADD VALUE IF NOT EXISTS (already implied by
-- this schema's use of JSONB/array columns elsewhere).

-- Backfill any enum values that may be missing for the same reason as the
-- columns above: if these enum types already existed (created by an earlier,
-- narrower version of this migration) before a value was added to the
-- CREATE TYPE list, that value never actually landed on the live type.
-- (ExpenseStatus.PARTIAL hit exactly this and was fixed in the previous
-- migration; this backfills every other enum value defensively too.)

